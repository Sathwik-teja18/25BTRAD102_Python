def atomic_write_text(path: Path, content: str) -> None:
    """Write to a temporary sibling then atomically replace the target."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            if not content.endswith("\n"):
                handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary_name, path)
    except Exception:
        try:
            os.unlink(temporary_name)
        except OSError:
            pass
        raise


def confirm(prompt: str) -> bool:
    try:
        answer = input(f"{prompt} [y/N] ").strip().lower()
    except (EOFError, KeyboardInterrupt):
        print("\n[GENESIS] Cancelled.")
        return False
    return answer in {"y", "yes"}


def slugify(text: str) -> str:
    value = re.sub(r"[^a-zA-Z0-9]+", "_", text.lower()).strip("_")
    return (value[:40].strip("_") or "new_skill")


def extract_python_code(response: str) -> str:
    match = re.search(r"```(?:python|py)?\s*(.*?)```", response, flags=re.DOTALL | re.IGNORECASE)
    if match:
        return match.group(1).strip()
    return response.strip()


def parse_json_object(text: str) -> dict[str, Any] | None:
    candidate = text.strip()
    if candidate.startswith("```"):
        candidate = re.sub(r"^```(?:json)?\s*", "", candidate, flags=re.IGNORECASE)
        candidate = re.sub(r"\s*```$", "", candidate)
    try:
        value = json.loads(candidate)
        return value if isinstance(value, dict) else None
    except json.JSONDecodeError:
        # Recover a single object if a model adds a short preamble.
        start, end = candidate.find("{"), candidate.rfind("}")
        if start >= 0 and end > start:
            try:
                value = json.loads(candidate[start:end + 1])
                return value if isinstance(value, dict) else None
            except json.JSONDecodeError:
                return None
    return None


def find_function(tree: ast.AST, function_name: str) -> ast.FunctionDef | ast.AsyncFunctionDef | None:
    for node in getattr(tree, "body", []):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == function_name:
            return node
    return None


def validate_python_source(source: str, required_functions: tuple[str, ...]) -> tuple[bool, str]:
    try:
        tree = ast.parse(source)
        compile(tree, "<candidate>", "exec")
    except (SyntaxError, ValueError, TypeError) as exc:
        line = getattr(exc, "lineno", None)
        return False, f"Syntax/compile validation failed{f' on line {line}' if line else ''}: {exc}"

    top_level_functions = {
        node.name for node in tree.body if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
    }
    missing = [name for name in required_functions if name not in top_level_functions]
    if missing:
        return False, "Missing required top-level function(s): " + ", ".join(missing)

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            roots = [alias.name.split(".", 1)[0] for alias in node.names]
            bad = [name for name in roots if name in BLOCKED_IMPORT_ROOTS]
            if bad:
                return False, f"Blocked import(s): {', '.join(sorted(set(bad)))}"
        elif isinstance(node, ast.ImportFrom):
            root = (node.module or "").split(".", 1)[0]
            if root in BLOCKED_IMPORT_ROOTS:
                return False, f"Blocked import: {root}"
        elif isinstance(node, ast.Call):
            if isinstance(node.func, ast.Name) and node.func.id in BLOCKED_CALL_NAMES:
                return False, f"Blocked call: {node.func.id}()"
            if isinstance(node.func, ast.Attribute) and node.func.attr in BLOCKED_ATTRIBUTE_CALLS:
                # Only block generic system/popen attributes when they are invoked
                # through APIs that can launch a shell; platform.system() is safe.
                if node.func.attr in {"system", "popen"}:
                    base = node.func.value
                    if isinstance(base, ast.Name) and base.id in {"os", "subprocess"}:
                        return False, f"Blocked risky call pattern: {base.id}.{node.func.attr}()"
                else:
                    return False, f"Blocked risky call pattern: .{node.func.attr}()"

    return True, "AST, compile, entry-point, and basic risk checks passed."


